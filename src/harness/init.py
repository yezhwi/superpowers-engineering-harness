"""Harness initialization core (guide sections 8-13).

Non-destructive by construction: existing files are skipped, never
overwritten; directories created only when missing.
"""

from dataclasses import dataclass, field
from pathlib import Path

from harness import templates as templates_mod
from harness.templates import TemplateNotFoundError

REQUIRED_FILES = (
    "current-task.yaml",
    "requirements.yaml",
    "invariants.yaml",
    "gate.yaml",
    "impact.yaml",
    "observability.yaml",
)

REQUIRED_DIRS = (
    "findings",
    "evidence",
    "decisions",
    "interface-contracts",
)


@dataclass
class InitResult:
    repo_root: Path
    harness_dir: Path
    created: list[Path] = field(default_factory=list)
    skipped: list[Path] = field(default_factory=list)


def _ensure_dir(path: Path) -> None:
    if not path.exists():
        path.mkdir(parents=True)


def init_harness(repo_root: Path, templates: Path | None = None) -> InitResult:
    """Initialize .harness/ under repo_root. Idempotent and non-destructive.

    created/skipped record FILES only; missing directories are silently
    ensured. Raises TemplateNotFoundError if any required template is
    missing.
    """
    repo_root = Path(repo_root)
    templates = Path(templates) if templates else templates_mod.templates_dir()

    missing = [name for name in REQUIRED_FILES if not (templates / name).is_file()]
    if missing:
        raise TemplateNotFoundError(
            f"missing required templates in {templates}: {missing}"
        )

    harness_dir = repo_root / ".harness"
    result = InitResult(repo_root=repo_root, harness_dir=harness_dir)

    _ensure_dir(harness_dir)
    for dirname in REQUIRED_DIRS:
        _ensure_dir(harness_dir / dirname)

    from ._scope_replay import SCOPE_FILES
    from .transaction_recovery import publication_recovery

    with publication_recovery(harness_dir):
        fresh = (not any((harness_dir / name).exists() or (harness_dir / name).is_symlink()
                         for name in (*REQUIRED_FILES, *SCOPE_FILES, 'decisions/index.yaml'))
                 and not list((harness_dir / 'decisions').glob('DEC-*.yaml')))
        if fresh:
            return _initialize_genesis(result, templates)

        # Compatibility maintenance shares recovery owner; never invent origin.
        for name in REQUIRED_FILES:
            target = harness_dir / name
            if target.exists():
                result.skipped.append(target)
                continue
            target.write_text(
                (templates / name).read_text(encoding="utf-8"),
                encoding="utf-8",
            )
            result.created.append(target)

        index = harness_dir / "decisions/index.yaml"
        if index.exists():
            result.skipped.append(index)
        else:
            members = list((harness_dir / "decisions").glob("DEC-*.yaml"))
            if members:
                from harness.decision import reindex

                reindex(harness_dir)
            else:
                index.write_text("decisions: []\n", encoding="utf-8")
            result.created.append(index)

        result.skipped.extend(harness_dir / name for name in SCOPE_FILES if (harness_dir / name).exists())
        return result


def _initialize_genesis(result: InitResult, templates: Path) -> InitResult:
    """Publish fresh task plus actual initial scope as one recoverable bundle."""
    import shutil
    import tempfile

    from . import transaction
    from ._scope_replay import new_scope_artifacts

    root = result.harness_dir
    # Sibling staging keeps project-relative test containment anchored to repo.
    with tempfile.TemporaryDirectory(prefix='.harness-genesis-', dir=result.repo_root) as temporary:
        staged = Path(temporary)
        for name in REQUIRED_FILES:
            shutil.copyfile(templates / name, staged / name)
        for artifact in new_scope_artifacts(staged):
            (staged / artifact.relative_path).write_bytes(artifact.content)
        names = (*REQUIRED_FILES, 'decisions/index.yaml', 'test-scope-baseline.yaml',
                 'test-scope-audit.yaml', 'test-scope-seal.yaml')
        (staged / 'decisions').mkdir()
        (staged / 'decisions/index.yaml').write_bytes(b'decisions: []\n')
        # Build scope against repository-relative sibling, then publish exact
        # generated bytes from normal managed staging, not arbitrary directories.
        artifacts = tuple(transaction.StagedArtifact(name, (staged / name).read_bytes()) for name in names)
        prepared = transaction.stage(root, list(artifacts))
        transaction.publish(root, prepared, durable=True, expected_sources={name: None for name in names},
                            expected_artifacts=artifacts)
        result.created.extend(root / name for name in names)
    return result


def init_current_repository(cwd: Path | None = None) -> InitResult:
    """Resolve the git repository root from `cwd` (default: Path.cwd())
    and initialize .harness/ there (guide section 21)."""
    from harness.repository import find_git_root

    start = Path(cwd) if cwd else Path.cwd()
    return init_harness(find_git_root(start))
